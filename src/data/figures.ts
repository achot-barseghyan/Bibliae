const DIACRITICS_PATTERN = new RegExp('[\\u0300-\\u036f]', 'g');

export function normalizeLetter(name: string): string {
  return name
    .normalize('NFD')
    .replace(DIACRITICS_PATTERN, '')
    .charAt(0)
    .toUpperCase();
}

